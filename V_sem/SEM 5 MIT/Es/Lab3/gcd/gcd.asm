	AREA RESET,DATA,READONLY
	EXPORT __Vectors
__Vectors
	DCD 0x10001000
	DCD Reset_Handler
	ALIGN
	AREA mycode,CODE,READONLY
	ENTRY
	EXPORT Reset_Handler
Reset_Handler
	MOV R1, #576
	MOV R2, #168
	LDR R3, =DST

GCD	CMP R1, R2
	BEQ EN
	BGT CO
	B CT

CO	SUB R1, R2
	B GCD
CT	SUB R2, R1
	B GCD

EN	STR R1, [R3] 
	
STOP
	B STOP

N DCD 0x0000000A, 0x00000001, 0x0000000D, 0x00000007, 0x00000004, 0x00000003, 0x0000000D, 0x0000000F
	AREA mydata, DATA, READWRITE
DST DCD 0, 0, 0, 0, 0, 0, 0, 0, 0