	DCD 0x10001000
	DCD Reset_Handler
	ALIGN
	AREA mycode,CODE,READONLY
	ENTRY
	EXPORT Reset_Handler
Reset_Handler
	MOV R10, #8
	LDR R0, =N
	LDR R1, =DST
	
UP	LDR R5, [R0], #4
	ADD R3, R5
	ROR R3, R3, #28
	SUBS R10, #1
	BNE UP
	ROR R3, R3, #4	
	STR R3, [R1]
	
STOP
	B STOP

N DCD 0x0000000A, 0x00000001, 0x0000000D, 0x00000007, 0x00000004, 0x00000003, 0x0000000D, 0x0000000F
	AREA mydata, DATA, READWRITE
