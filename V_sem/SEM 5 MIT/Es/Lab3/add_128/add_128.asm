__Vectors
	DCD 0x10001000
	DCD Reset_Handler
	ALIGN
	AREA mycode,CODE,READONLY
	ENTRY
	EXPORT Reset_Handler
Reset_Handler
	LDR R0, =N1
	LDR R1, =N2
	LDR R9, =DST
	MOV R10, #4
	
UP	LDR R2, [R0], #4
	LDR R3, [R1], #4
	ADCS R5, R3, R2
	STR R5, [R9], #4
	SUB R10, #1
	TEQ R10, #00
	BNE UP
	
STOP
	B STOP

N1 DCD 0x11111111, 0x11111111, 0x11111111, 0x11111111
N2 DCD 0x22222222, 0x33334444, 0x44445555, 0x66778899
